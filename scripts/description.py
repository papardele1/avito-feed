def specs(it, prof):
    rows = []
    if prof.get("Model"):
        rows.append(("Модель", f"{prof.get('Vendor', '')} {prof['Model']}".strip()))
    if it.get("memory"):
        rows.append(("Память", it["memory"]))
    if it.get("ram"):
        rows.append(("Оперативная память", it["ram"]))
    if it.get("color_src"):
        ru = prof.get("Color")
        rows.append(("Цвет", f"{it['color_src']} ({ru})" if ru and ru[0].islower() else it["color_src"]))
    if it.get("sim") in SIM_TEXT:
        rows.append(("SIM", SIM_TEXT[it["sim"]]))
    if it.get("region") in REGION_TEXT:
        rows.append(("Версия", REGION_TEXT[it["region"]]))
    if it.get("chip"):
        rows.append(("Процессор", it["chip"]))
    return rows


